#!/usr/bin/env python3
"""
build_eval_figures.py — Render two analytical figures from metrics JSON.

Reads:
    papers/tg-roger-joshua/sections/_auto/metrics_<safe>.json   (default qwen2.5)
    papers/tg-roger-joshua/sections/_auto/models_comparison.json

Writes (under papers/tg-roger-joshua/figures/_auto/):
    per_class_f1_support.tex   — horizontal bars: F1 (%) per class, with
                                 gold support annotated; sorted by support
                                 descending. Visualizes the small-N effect:
                                 classes with support <=2 collapse to F1=0,
                                 dragging the macro average down.
    precision_recall_gap.tex   — grouped horizontal bars: precision vs recall
                                 per class. Surfaces the granularity gap:
                                 classes whose precision is high but recall is
                                 low are exactly the gold parents (e.g.,
                                 Information systems, Software engineering)
                                 that the model splits into more specific
                                 IEEE children.

USAGE
    bash containers/run.sh paper-data \\
        python papers/tg-roger-joshua/scripts/build_eval_figures.py \\
        --model qwen2.5:14b-instruct
"""
from __future__ import annotations
import argparse
import json
import sys
from pathlib import Path

PAPER = Path(__file__).resolve().parent.parent
AUTO  = PAPER / "sections" / "_auto"
FIGS  = PAPER / "figures" / "_auto"

SHORT = {
    "Information systems":            "IS",
    "Database management systems":    "DB",
    "Enterprise information systems": "EIS",
    "Web applications":               "Web",
    "Mobile applications":            "Mob",
    "Software engineering":           "SE",
    "Artificial intelligence":        "AI",
    "Machine learning":               "ML",
    "Natural language processing":    "NLP",
    "Image processing":               "IP",
    "Computer vision":                "CV",
    "Recommender systems":            "Rec",
    "Data mining":                    "DM",
    "Ontologies":                     "Ont",
    "Multi-agent systems":            "MAS",
    "Cybersecurity":                  "Sec",
    "Constraint programming":         "CP",
    "Complex networks":               "CN",
    "Internet of Things":             "IoT",
    "Gamification":                   "Gam",
    "Serious games":                  "SG",
    "E-learning":                     "EL",
    "Other":                          "Oth",
}


def safe_tag(model: str) -> str:
    return model.replace(":", "_").replace("/", "_")


def render_per_class_f1(metrics: dict, model: str) -> str:
    rows = sorted(
        [(lbl, p["f1"], p["support"]) for lbl, p in metrics["per_class"].items()
         if p["support"] > 0],
        key=lambda r: (-r[2], -r[1]),
    )
    coords_f1 = " ".join(f"({f1*100:.1f},{i})" for i, (_, f1, _) in enumerate(rows))
    nodes_supp = "\n".join(
        f"      \\node[anchor=west,font=\\scriptsize] at (axis cs:{f1*100:.1f},{i})"
        f" {{ \\,N{{=}}{s} }};"
        for i, (_, f1, s) in enumerate(rows)
    )
    yticks = ",".join(str(i) for i in range(len(rows)))
    yticklabels = ",".join(SHORT.get(lbl, lbl) for lbl, _, _ in rows)
    cap = (
        f"Per-class $F_1$ (\\%) of \\texttt{{{model}}} on the gold set, "
        "sorted by gold support (annotated next to each bar). Classes whose "
        "support is one or two collapse to $F_1{=}0$ and pull the macro "
        "average down."
    )
    return (
        "% Auto-generated by scripts/build_eval_figures.py — do not edit.\n"
        "\\begin{figure}[t]\n"
        "  \\centering\n"
        "  \\begin{tikzpicture}\n"
        "    \\begin{axis}[\n"
        "      width=0.95\\linewidth, height=7.5cm,\n"
        "      xbar, xmin=0, xmax=110,\n"
        "      bar width=4pt, enlarge y limits=0.04,\n"
        "      xlabel={$F_1$ (\\%)},\n"
        f"      ytick={{{yticks}}},\n"
        f"      yticklabels={{{yticklabels}}},\n"
        "      yticklabel style={font=\\scriptsize},\n"
        "      tick align=outside,\n"
        "      nodes near coords style={font=\\tiny},\n"
        "      ]\n"
        f"      \\addplot+[fill=blue!55,draw=blue!70!black] coordinates {{{coords_f1}}};\n"
        f"{nodes_supp}\n"
        "    \\end{axis}\n"
        "  \\end{tikzpicture}\n"
        f"  \\caption{{{cap}}}\n"
        "  \\label{fig:per-class-f1}\n"
        "\\end{figure}\n"
    )


def render_precision_recall(metrics: dict, model: str) -> str:
    rows = sorted(
        [(lbl, p["precision"], p["recall"], p["support"])
         for lbl, p in metrics["per_class"].items() if p["support"] > 0],
        key=lambda r: -r[3],
    )
    coords_p = " ".join(f"({p*100:.1f},{i})" for i, (_, p, _, _) in enumerate(rows))
    coords_r = " ".join(f"({r*100:.1f},{i})" for i, (_, _, r, _) in enumerate(rows))
    yticks = ",".join(str(i) for i in range(len(rows)))
    yticklabels = ",".join(SHORT.get(lbl, lbl) for lbl, _, _, _ in rows)
    cap = (
        f"Per-class precision and recall of \\texttt{{{model}}} on the gold "
        "set. Classes for which precision is high but recall is low "
        "({IS}, {SE}) are gold parents that the model legitimately splits "
        "into more specific {IEEE} children, the granularity gap discussed "
        "in \\cref{sec:res-o1}."
    )
    return (
        "% Auto-generated by scripts/build_eval_figures.py — do not edit.\n"
        "\\begin{figure}[t]\n"
        "  \\centering\n"
        "  \\begin{tikzpicture}\n"
        "    \\begin{axis}[\n"
        "      width=0.95\\linewidth, height=7.5cm,\n"
        "      xbar, xmin=0, xmax=110,\n"
        "      bar width=3pt, enlarge y limits=0.04,\n"
        "      xlabel={Score (\\%)},\n"
        f"      ytick={{{yticks}}},\n"
        f"      yticklabels={{{yticklabels}}},\n"
        "      yticklabel style={font=\\scriptsize},\n"
        "      legend style={font=\\scriptsize,at={(0.98,0.02)},anchor=south east},\n"
        "      legend cell align=left,\n"
        "      ]\n"
        f"      \\addplot+[fill=blue!55,draw=blue!70!black] coordinates {{{coords_p}}}; \\addlegendentry{{Precision}}\n"
        f"      \\addplot+[fill=orange!75,draw=orange!80!black] coordinates {{{coords_r}}}; \\addlegendentry{{Recall}}\n"
        "    \\end{axis}\n"
        "  \\end{tikzpicture}\n"
        f"  \\caption{{{cap}}}\n"
        "  \\label{fig:precision-recall-gap}\n"
        "\\end{figure}\n"
    )


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__,
                                  formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--model", default="qwen2.5:14b-instruct",
                    help="Ollama model tag whose metrics_*.json will drive the figures")
    args = ap.parse_args()

    metrics_file = AUTO / f"metrics_{safe_tag(args.model)}.json"
    if not metrics_file.exists():
        print(f"ERROR: missing {metrics_file}", file=sys.stderr)
        return 2

    metrics = json.loads(metrics_file.read_text())
    FIGS.mkdir(parents=True, exist_ok=True)

    out1 = FIGS / "per_class_f1_support.tex"
    out1.write_text(render_per_class_f1(metrics, args.model), encoding="utf-8")
    print(f"Wrote {out1.relative_to(PAPER.parent.parent)}")

    out2 = FIGS / "precision_recall_gap.tex"
    out2.write_text(render_precision_recall(metrics, args.model), encoding="utf-8")
    print(f"Wrote {out2.relative_to(PAPER.parent.parent)}")

    return 0


if __name__ == "__main__":
    sys.exit(main())
